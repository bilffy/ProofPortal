<?php

namespace App\Http\Livewire\Products;

use App\Http\Resources\UserResource;
use App\Models\CustomField;
use App\Models\Product;
use Illuminate\Support\Facades\DB;
use Auth;
use Livewire\Component;
use Livewire\WithFileUploads;

class ProductsList extends Component
{
    use WithFileUploads;

    private const DRAFT_NAME = 'New Product';

    public $products = [];

    public bool $showForm = false;
    public ?int $editingId = null;
    public bool $isDraft = false;

    // Form state
    public string $name = '';
    public string $slug = '';
    public string $description = '';
    public string $sku = '';
    public $basePrice = '';
    public bool $isActive = true;
    public $sortOrder = 0;
    public $image = null; // new upload, if any
    public ?string $existingImagePath = null;

    /**
     * Custom fields assigned to the product being added/edited, in display
     * order. Kept here (not saved on drop) so assignments are only written
     * when Create Product / Save Changes is clicked.
     *
     * @var array<int, int|string>
     */
    public array $assignedFieldIds = [];

    public string $successMessage = '';

    protected function rules(): array
    {
        return [
            'name' => 'required|string|max:255',
            'slug' => 'nullable|string|max:255|alpha_dash',
            'description' => 'nullable|string',
            'sku' => 'nullable|string|max:255|unique:products,sku,' . ($this->editingId ?: 'NULL') . ',id',
            'basePrice' => 'nullable|numeric|min:0',
            'isActive' => 'boolean',
            'sortOrder' => 'nullable|integer|min:0',
            'image' => 'nullable|image|max:5120',
            'assignedFieldIds' => 'array',
            'assignedFieldIds.*' => 'integer',
        ];
    }

    public function mount()
    {
        if (!Auth::user()->isSuperAdmin()) {
            return redirect()->route('dashboard');
        }

        // Add Product no longer creates a placeholder row, but older versions
        // did, and any such draft that had fields dragged into it was kept
        // forever. A draft is recognisable because it was only ever written by
        // createNew(): named "New Product", inactive, and with no slug (the
        // slug is only generated by a real Create/Save). Remove those leftovers.
        Product::where('name', self::DRAFT_NAME)
            ->where('is_active', false)
            ->where(fn ($q) => $q->whereNull('slug')->orWhere('slug', ''))
            ->delete();

        $this->loadProducts();
    }

    public function loadProducts(): void
    {
        $this->products = Product::orderBy('sort_order')->orderBy('name')->get();
    }

    public function createNew(): void
    {
        $this->resetForm();
        $this->sortOrder = (int) (Product::max('sort_order') ?? 0) + 1;

        // Nothing is written until Create Product - the product row and its
        // field assignments are saved together by save().
        $this->isDraft = true;
        $this->showForm = true;
        $this->successMessage = '';
    }

    public function edit(int $id): void
    {
        $product = Product::findOrFail($id);

        $this->editingId = $product->id;
        $this->isDraft = false;
        $this->name = $product->name;
        $this->slug = (string) $product->slug;
        $this->description = (string) $product->description;
        $this->sku = (string) $product->sku;
        // $this->basePrice = $product->base_price !== null ? (string) $product->base_price : '';
        $this->isActive = (bool) $product->is_active;
        $this->sortOrder = (int) $product->sort_order;
        $this->existingImagePath = $product->image;
        $this->image = null;
        $this->assignedFieldIds = $product->customFields()->pluck('custom_fields.id')->map(fn ($id) => (int) $id)->all();

        $this->showForm = true;
        $this->successMessage = '';
    }

    public function save(): void
    {
        $this->validate();

        $product = $this->editingId
            ? Product::findOrFail($this->editingId)
            : new Product();

        $product->name = $this->name;
        $product->slug = $this->slug !== ''
            ? $this->slug
            : Product::generateUniqueSlug($this->name, $this->editingId);
        $product->description = $this->description ?: null;
        $product->sku = $this->sku ?: null;
        // $product->base_price = $this->basePrice !== '' ? $this->basePrice : null;
        $product->is_active = $this->isActive;
        $product->sort_order = $this->sortOrder !== '' ? (int) $this->sortOrder : 0;

        if ($this->image) {
            $path = $this->image->store('products', 'public');
            $product->image = $path;
        }

        DB::transaction(function () use ($product) {
            $product->save();

            // Assigned fields + their drag order, saved together with the product.
            $ids = array_values(array_unique(array_map('intval', $this->assignedFieldIds)));
            $validIds = CustomField::whereIn('id', $ids)->pluck('id')->map(fn ($id) => (int) $id)->all();

            $pivotData = [];
            foreach (array_values(array_intersect($ids, $validIds)) as $index => $fieldId) {
                $pivotData[$fieldId] = ['sort_order' => $index];
            }

            $product->customFields()->sync($pivotData);
        });

        $this->successMessage = $this->isDraft ? 'Product created.' : 'Product updated.';

        $this->resetForm();
        $this->showForm = false;
        $this->loadProducts();
    }

    public function delete(int $id): void
    {
        $product = Product::findOrFail($id);
        $product->delete();

        $this->successMessage = 'Product deleted.';
        $this->loadProducts();
    }

    public function cancel(): void
    {
        $this->resetForm();
        $this->showForm = false;
    }

    private function resetForm(): void
    {
        $this->editingId = null;
        $this->isDraft = false;
        $this->name = '';
        $this->slug = '';
        $this->description = '';
        $this->sku = '';
        $this->basePrice = '';
        $this->isActive = true;
        $this->sortOrder = 0;
        $this->image = null;
        $this->existingImagePath = null;
        $this->assignedFieldIds = [];
        $this->resetErrorBag();
    }

    public function render()
    {
        return view('livewire.products.products-list')
            ->layout('layouts.authenticated', [
                'user' => new UserResource(Auth::user()),
            ]);
    }
}
